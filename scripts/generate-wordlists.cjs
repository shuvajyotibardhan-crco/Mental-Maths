const sowpods = require('sowpods')
const fs = require('fs')
const path = require('path')

const outDir = path.join(__dirname, '../src/data/wordlists')
fs.mkdirSync(outDir, { recursive: true })

for (let len = 3; len <= 8; len++) {
  const words = sowpods.filter(w => w.length === len)
  const lines = words.map(w => `'${w}'`).join(',\n  ')
  const content = `// SOWPODS word list — ${len}-letter words (${words.length} total)\n// Auto-generated by scripts/generate-wordlists.cjs — do not edit manually\nconst words: ReadonlySet<string> = new Set([\n  ${lines}\n])\nexport default words\n`
  fs.writeFileSync(path.join(outDir, `wom-${len}.ts`), content)
  console.log(`wom-${len}.ts: ${words.length} words`)
}
